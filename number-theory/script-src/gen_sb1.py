out = []
out.append(open('sb1_head.md', encoding='utf-8').read())
t = 0.0; n = 0
for sid, name, sub, pics, keys in SC:
    d = L[sid]
    out.append(f'\n## {mmss(t)}–{mmss(t + d["dur"])} · {name}（{sub}）\n')
    out.append('**画面**\n')
    for p in pics: out.append(f'- {p}')
    out.append('\n**台词**\n')
    for s in d['subs']:
        n += 1
        who = WHO[s.get('voice')]
        txt = s['text'].strip('“”')
        say = f'（读作：{s["say"]}）' if ('say' in s and any(c.isdigit() for c in s['text'])) else ''
        mark = '〔片名卡，不出字幕〕' if s.get('hide') else ''
        out.append(f'{n}. **{who}**：{txt}{say}{mark}')
    if keys:
        out.append('\n**关键镜头**\n')
        out.append('| 镜头 | 观众在问什么 | 画面展示哪一步 | 旁白补哪条理由 | 依赖什么条件 | 可能造成的误解与防法 |')
        out.append('|---|---|---|---|---|---|')
        for k in keys: out.append('| ' + ' | '.join(k) + ' |')
    if sid == 'pause1':
        out.append('\n> **暂停点 1**：在第 ' + str(n - 6) + ' 句后停住。')
    t += d['dur']
out.append(open('sb1_tail.md', encoding='utf-8').read())
